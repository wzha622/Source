_NETS = None


def _nets():
    global _NETS
    if _NETS is None:
        _NETS = []
        for vendor, cidrs in CDN_CIDR.items():
            for c in cidrs:
                try:
                    _NETS.append((vendor, ipaddress.ip_network(c, strict=False)))
                except ValueError:
                    pass
    return _NETS


def cdn_vendor_of(ip, org=None):
    """返回 CDN 厂商名，不是 CDN 返回 None"""
    try:
        addr = ipaddress.ip_address(ip)
    except ValueError:
        return None
    for vendor, net in _nets():
        if addr.version == net.version and addr in net:
            return vendor
    if org:
        o = str(org).lower()
        for hint, vendor in CDN_ORG_HINTS:
            if hint in o:
                return vendor
    return None


def is_cdn(ip, org=None):
    return cdn_vendor_of(ip, org) is not None


def cidr_of(ip, prefix=24):
    """把 IP 转成 /24 网段，用于旁站扫描"""
    try:
        net = ipaddress.ip_network(f"{ip}/{prefix}", strict=False)
        return str(net)
    except ValueError:
        return None
